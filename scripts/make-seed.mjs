// Writes db/seed.sql from content/data.json, so the database can be filled with exactly what the
// site shows today. Run: node scripts/make-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../content/data.json", import.meta.url), "utf8"));

const q = (v) => (v === undefined || v === null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const num = (v) => (v === undefined || v === null ? "null" : String(v));
const bool = (v) => (v ? "true" : "false");
const arr = (a) => (a === undefined || a === null ? "null" : `array[${a.map(q).join(", ")}]::text[]`);
const json = (v) => (v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const rows = (table, cols, list) =>
  list.length
    ? `insert into portfolio.${table} (${cols.join(", ")}) values\n${list.map((r) => `  (${r.join(", ")})`).join(",\n")};\n`
    : "";

const p = data.profile;
let sql = `-- Generated by scripts/make-seed.mjs from content/data.json. Fills the tables from db/schema.sql
-- with everything currently on the site. Re-running replaces the content (one transaction).

begin;

truncate portfolio.profile, portfolio.profile_links, portfolio.schooling, portfolio.timeline,
  portfolio.stack_items, portfolio.systems, portfolio.achievements, portfolio.moments,
  portfolio.publications, portfolio.companies restart identity;

`;

sql += rows(
  "profile",
  ["name", "first_name", "last_name", "role", "company", "location", "headline", "summary", "education", "email", "phone_display", "phone_href", "resume", "site_url", "portrait", "interests"],
  [[q(p.name), q(p.firstName), q(p.lastName), q(p.role), q(p.company), q(p.location), q(p.headline), q(p.summary), q(p.education), q(p.email), q(p.phone.display), q(p.phone.href), q(p.resume), q(p.siteUrl), json(p.portrait), arr(p.interests)]],
);
sql += "\n" + rows("profile_links", ["sort", "label", "href", "handle"], p.links.map((l, i) => [i, q(l.label), q(l.href), q(l.handle)]));
sql += "\n" + rows("schooling", ["sort", "degree", "school", "score", "period"], p.schooling.map((s, i) => [i, q(s.degree), q(s.school), q(s.score), q(s.period)]));
sql +=
  "\n" +
  rows(
    "timeline",
    ["sort", "period", "kind", "title", "org", "span_start", "span_end", "points", "tags"],
    data.timeline.map((t, i) => [i, q(t.period), q(t.kind), q(t.title), q(t.org), num(t.span?.[0]), num(t.span?.[1]), arr(t.points), arr(t.tags)]),
  );
sql +=
  "\n" +
  rows(
    "stack_items",
    ["layer", "sort", "item"],
    Object.entries(data.stack).flatMap(([layer, items]) => items.map((it, i) => [q(layer), i, q(it)])),
  );
sql +=
  "\n" +
  rows(
    "systems",
    ["slug", "sort", "name", "summary", "domains", "stack", "ships_as", "platform", "org", "internal", "links", "logo", "screen", "points", "architecture"],
    data.systems.map((s, i) => [q(s.slug), i, q(s.name), q(s.summary), arr(s.domains), arr(s.stack), q(s.shipsAs), q(s.platform), q(s.org), bool(s.internal), json(s.links), q(s.logo), json(s.screen), arr(s.points), json(s.architecture)]),
  );
sql +=
  "\n" +
  rows(
    "achievements",
    ["sort", "kind", "title", "org", "year", "status", "detail", "image"],
    data.achievements.map((a, i) => [i, q(a.kind), q(a.title), q(a.org), q(a.year), q(a.status), q(a.detail), json(a.image)]),
  );
sql +=
  "\n" +
  rows(
    "moments",
    ["when_year", "date_label", "place", "title", "caption", "image", "fit"],
    data.moments.map((m) => [num(m.when), q(m.date), q(m.place), q(m.title), q(m.caption), json(m.image), q(m.fit)]),
  );
sql +=
  "\n" +
  rows(
    "publications",
    ["sort", "kind", "title", "authors", "venue", "date_label", "year", "id_label", "id_value", "abstract", "href", "image", "tags"],
    data.publications.map((x, i) => [i, q(x.kind), q(x.title), arr(x.authors), q(x.venue), q(x.date), num(x.year), q(x.id?.label), q(x.id?.value), q(x.abstract), q(x.href), json(x.image), arr(x.tags)]),
  );
sql +=
  "\n" +
  rows(
    "companies",
    ["sort", "name", "tagline", "about", "role", "since", "url", "tone", "logo", "links"],
    (data.companies ?? []).map((c, i) => [i, q(c.name), q(c.tagline), q(c.about), q(c.role), q(c.since), q(c.url), q(c.tone), json(c.logo), json(c.links)]),
  );
sql += "\ncommit;\n";

writeFileSync(new URL("../db/seed.sql", import.meta.url), sql);
console.log("wrote db/seed.sql");
